"""Системный промпт для модели и сборка пользовательского промпта.

Правила, которые экономят время на guard-слое:
- модели ЗАПРЕЩЕНО придумывать цены и сроки (это зашито в системный промпт);
- цены и каноническая строка срока добавляются в КП только кодом (price.py / service.py);
- перед отправкой промпт обезличивается от ПДн функцией depersonalize (guard.py).
"""
from __future__ import annotations

from src.price import price_number_label

SYSTEM_PROMPT = """Ты — опытный автор коммерческих предложений (КП) сервисной компании, оказывающей услуги по поддержке и сопровождению информационных систем и бизнес-процессов клиентов.

Твоя задача: по данным брифа написать текст КП по разделам шаблона.

СТРОГИЕ ПРАВИЛА:
1. Пиши текст строго по разделам шаблона, в том же порядке. Не пропускай разделы и не добавляй новых.
2. Каждый раздел начинай с заголовка в формате: ## Название раздела (решетка и пробел). Заголовок — ровно как в шаблоне.
3. НИКОГДА не указывай никакие цены, суммы, стоимость, тарифы, бюджеты в числах. Деньги формируются отдельной таблицей в прайсе компании, это не твоя зона. Любые числа с признаками денег (₽, руб., рублей, тыс., млн, USD, EUR) в тексте — запрещены.
4. НИКОГДА не придумывай сроки и даты. Используй только срок из брифа, дословно в разделе «Сроки». Если срока в брифе нет — напиши «Сроки согласуем отдельно».
5. Не выдумывай контактные данные, телефоны, e-mail, имена конкретных людей, реквизиты, адреса, лицензии, сертификаты. Если данных не хватает — пиши «уточним отдельно» или «согласуем дополнительно», не заполняй пробелы выдумкой.
6. Тон: деловой, уверенный, конкретный, на русском языке. Без канцеляритов и воды.
7. В разделе с услугами опиши состав работ и подход к выполнению, но БЕЗ цифр стоимости.
8. Не упоминай внутренние детали: «прайс», «бриф», «модель», «шаблон», «промпт»."""


def build_user_prompt(brief, sections, services) -> str:
    """Собирает пользовательский промпт: бриф + услуги (цены только для справки) + разделы.

    brief: src.brief.Brief
    sections: список разделов [{"header", "instruction"}]
    services: список словарей услуг из прайса (src.storage)
    """
    lines = ["Подготовь КП по следующим данным."]
    lines.append("")
    lines.append("ДАННЫЕ ИЗ БРИФА:")
    lines.append(f"Клиент: {brief.client}")
    lines.append(f"Задача: {brief.task}")
    lines.append(f"Сроки: {brief.deadline or 'не указаны'}")
    lines.append(f"Бюджет: {brief.budget or 'не указан'}")
    lines.append("")

    lines.append("ВЫБРАННЫЕ УСЛУГИ (цены показаны только для справки — НЕ включай их в текст):")
    for s in services:
        label = price_number_label(s.get("price"), s.get("unit") or "")
        lines.append(f"- {s['name']} — {label}")
    lines.append("")

    lines.append("РАЗДЕЛЫ ШАБЛОНА (соблюдай ровно эти разделы в этом порядке):")
    for i, sec in enumerate(sections, 1):
        lines.append(f"{i}. {sec['header']}: {sec.get('instruction', '')}")
    lines.append("")
    lines.append(
        "Начинай ответ сразу с первого раздела в формате «## Название раздела», без предисловий."
    )
    return "\n".join(lines)